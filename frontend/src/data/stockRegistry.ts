function cleanQuery(q: string): string {
  return q.toLowerCase().replace(/[^a-z0-9]/g, '').trim();
}

/**
 * Searches the registry with symbol prefix matching, company name matching,
 * alias matching, sector filtering, and typo-tolerant fuzzy search.
 */
export function searchStocks(query: string, limit = 15, sectorFilter = 'ALL'): StockInfo[] {
  let pool = MASTER_STOCK_REGISTRY;

  if (sectorFilter && sectorFilter !== 'ALL') {
    if (sectorFilter === 'NIFTY 50') {
      pool = pool.slice(0, 50);
    } else {
      const sf = sectorFilter.toLowerCase();
      pool = pool.filter(s => s.sector.toLowerCase().includes(sf.replace(/&.*/, '').trim()));
    }
  }

  if (!query || !query.trim()) {
    if (sectorFilter && sectorFilter !== 'ALL') {
      return pool.slice(0, limit);
    }
    return MASTER_STOCK_REGISTRY.filter(s => s.isHot).slice(0, limit);
  }

  const raw = query.trim().toLowerCase();
  const clean = cleanQuery(query);

  const scored: Array<{ stock: StockInfo; score: number }> = [];

  for (const stock of pool) {
    const symClean = cleanQuery(stock.symbol);
    const nameLower = stock.name.toLowerCase();
    const sectorLower = stock.sector.toLowerCase();

    let score = 0;

    // 1. Exact symbol match
    if (symClean === clean) {
      score += 100;
    }
    // 2. Exact alias match (handles "tatamoters" -> TATAMOTORS)
    else if (stock.aliases.some(a => cleanQuery(a) === clean)) {
      score += 90;
    }
    // 3. Symbol starts with query
    else if (symClean.startsWith(clean)) {
      score += 75;
    }
    // 4. Company name starts with query
    else if (nameLower.startsWith(raw)) {
      score += 65;
    }
    // 5. Company name contains query
    else if (nameLower.includes(raw)) {
      score += 50;
    }
    // 6. Aliases contain or start with query
    else if (stock.aliases.some(a => a.toLowerCase().includes(raw))) {
      score += 45;
    }
    // 7. Symbol contains query
    else if (symClean.includes(clean)) {
      score += 35;
    }
    // 8. Sector matches query
    else if (sectorLower.includes(raw)) {
      score += 20;
    }
    // 9. Substring fuzzy match for typos
    else if (clean.length >= 4) {
      for (const a of stock.aliases) {
        const ca = cleanQuery(a);
        if (ca.includes(clean) || clean.includes(ca)) {
          score += 40;
          break;
        }
      }
    }

    if (score > 0) {
      scored.push({ stock, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map(s => s.stock);
}

/**
 * Resolves any raw query or typo into a canonical StockInfo, or null if unknown.
 */
export function resolveStock(query: string): StockInfo | null {
  if (!query || !query.trim()) return null;
  const matches = searchStocks(query, 1);
  return matches.length > 0 ? matches[0] : null;
}

/**
 * Given any symbol string (e.g. "TATAMOTERS", "TATAMOTORS.NS", "WMT"),
 * returns the clean display ticker symbol without suffix.
 */
export function getCleanSymbol(symbol: string): string {
  const resolved = resolveStock(symbol);
  if (resolved) return resolved.symbol;
  return symbol.trim().toUpperCase().replace(/\.(NS|BO)$/i, '');
}

/**
 * Returns currency symbol for a given stock ticker.
 */
export function getCurrencyForSymbol(symbol: string): '₹' | '$' {
  const resolved = resolveStock(symbol);
  return resolved?.currency ?? '₹';
}
